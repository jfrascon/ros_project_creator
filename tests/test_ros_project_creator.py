def test_create_ros2_project_delegates_docker_generation(fake_active_user: Path, fake_docker_generator) -> None:
    project_dir = fake_active_user / 'demo_project'

    RosProjectCreator(
        project_id='demo',
        project_dir=project_dir,
        ros_distro='jazzy',
        base_img='ros:jazzy',
        image_main_user='developer',
        img_id='demo:latest',
        use_vscode_project=False,
        use_pre_commit=False,
        use_console_log=False,
    )

    assert len(fake_docker_generator) == 1
    docker_config = fake_docker_generator[0]
    assert docker_config.image_main_user == 'developer'
    assert docker_config.ros_distro == 'jazzy'
    assert docker_config.img_id == 'demo:latest'
    assert docker_config.output_dir == project_dir / 'docker'
    assert docker_config.rosdep_packages_dir == '../src'

    assert project_dir.joinpath('docker/Dockerfile').is_file()
    assert project_dir.joinpath('docker/build.py').is_file()
    assert project_dir.joinpath('docker/docker-compose.yaml').is_file()
    assert project_dir.joinpath('docker/.resources').is_dir()
    assert not project_dir.joinpath('docker/docker-compose-dev.yaml').exists()

    assert project_dir.joinpath('deps.repos').is_file()
    assert project_dir.joinpath('src/0_deps').is_dir()
    assert project_dir.joinpath('src/bringup/package.xml').is_file()
    assert project_dir.joinpath('src/simulation/package.xml').is_file()


def test_create_ros2_project_with_vscode_renders_templates(fake_active_user: Path, fake_docker_generator) -> None:
    project_dir = fake_active_user / 'demo_vscode'

    RosProjectCreator(
        project_id='demo_vscode',
        project_dir=project_dir,
        ros_distro='jazzy',
        base_img='ros:jazzy',
        image_main_user='developer',
        img_id='demo/vscode:latest',
        use_vscode_project=True,
        use_pre_commit=False,
        use_console_log=False,
    )

    generated_files = [
        project_dir / '.devcontainer/devcontainer.json',
        project_dir / '.devcontainer/code-devcont',
        project_dir / '.devcontainer/devcont',
        project_dir / '.devcontainer/docker-compose.yaml',
        project_dir / '.vscode/c_cpp_properties.json',
        project_dir / '.vscode/tasks.json',
        project_dir / 'ws.code-workspace',
    ]

    for generated_file in generated_files:
        assert generated_file.is_file()
        text = generated_file.read_text()
        assert '{{' not in text
        assert '}}' not in text

    devcontainer = json.loads(project_dir.joinpath('.devcontainer/devcontainer.json').read_text())

    compose_text = project_dir.joinpath('.devcontainer/docker-compose.yaml').read_text()
    code_devcont_script = project_dir.joinpath('.devcontainer/code-devcont')
    devcont_script = project_dir.joinpath('.devcontainer/devcont')

    assert 'demo/vscode:latest' in compose_text
    assert '${HOST_UID:?HOST_UID must be set}' in compose_text
    assert '${HOST_UPGID:?HOST_UPGID must be set}' in compose_text
    assert '${HOST_XAUTHORITY_FILE:?HOST_XAUTHORITY_FILE must be set}' in compose_text
    assert '${RENDER_GID:?RENDER_GID must be set}' in compose_text
    assert '${HOME}/demo_vscode:/home/developer/workspace' in compose_text
    assert 'XDG_RUNTIME_DIR: "/run/user/${HOST_UID:?HOST_UID must be set}"' in compose_text
    assert 'XAUTHORITY: "/run/user/${HOST_UID:?HOST_UID must be set}/docker-xwayland.xauth"' in compose_text
    assert 'CONTAINER_ROS_WORKSPACE: "/home/developer/workspace"' in compose_text
    assert (
        '- /run/user/${HOST_UID:?HOST_UID must be set}:mode=700,'
        'uid=${HOST_UID:?HOST_UID must be set},gid=${HOST_UPGID:?HOST_UPGID must be set}' in compose_text
    )
    assert str(fake_active_user) not in compose_text
    assert '.gitconfig' not in compose_text
    assert 'config/git' not in compose_text
    assert not project_dir.joinpath('.devcontainer/.env').exists()
    assert os.access(code_devcont_script, os.X_OK)
    assert os.access(devcont_script, os.X_OK)
    assert 'getopt' in code_devcont_script.read_text()
    assert 'getopt' in devcont_script.read_text()
    assert 'HOST_XAUTHORITY_FILE' in code_devcont_script.read_text()
    assert 'HOST_XAUTHORITY_FILE' in devcont_script.read_text()
    assert '/run/user/$(id -u)/docker-xwayland.xauth' in code_devcont_script.read_text()
    assert '/run/user/$(id -u)/docker-xwayland.xauth' in devcont_script.read_text()
    assert 'require_env XDG_RUNTIME_DIR' not in devcont_script.read_text()
    assert '--up' in devcont_script.read_text()
    assert '--down' in devcont_script.read_text()
    assert devcontainer['updateRemoteUserUID'] is True
    assert devcontainer['overrideCommand'] is False
    assert devcontainer['containerUser'] == 'root'
    assert devcontainer['remoteUser'] == 'developer'
    assert '"ROS2.distro": "jazzy"' in project_dir.joinpath('ws.code-workspace').read_text()


