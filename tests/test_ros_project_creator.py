def test_code_devcont_exports_image_identity_without_writing_env(fake_active_user: Path, tmp_path: Path) -> None:
    project_dir = fake_active_user / 'code_devcontainer'
    _create_project(project_dir, use_vscode_project=True)
    fake_bin, command_log = _create_fake_devcontainer_commands(tmp_path)
    xauthority_file = tmp_path / 'docker-xwayland.xauth'
    render_device = tmp_path / 'renderD128'
    xauthority_file.touch()
    render_device.touch()
    environment = os.environ.copy()
    environment.update(
        {
            'COMMAND_LOG': str(command_log),
            'DISPLAY': ':99',
            'HOST_XAUTHORITY_FILE': str(xauthority_file),
            'PATH': f'{fake_bin}:{environment["PATH"]}',
            'RENDER_DEVICE': str(render_device),
        }
    )

    completed = subprocess.run(
        [str(project_dir / '.devcontainer/code-devcont')], text=True, capture_output=True, env=environment
    )

    assert completed.returncode == 0, completed.stdout + completed.stderr
    command_output = command_log.read_text()
    assert 'docker image inspect' in command_output
    assert 'identity=21001:21002' in command_output
    assert 'compose-project=demo' in command_output
    assert f'code {project_dir / "ws.code-workspace"}' in command_output
    assert not project_dir.joinpath('.devcontainer/.env').exists()
    assert not project_dir.joinpath('docker/.env').exists()


