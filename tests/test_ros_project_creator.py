def test_devcont_down_reuses_existing_development_env(fake_active_user: Path, tmp_path: Path) -> None:
    project_dir = fake_active_user / 'stop_devcontainer'
    _create_project(project_dir, use_vscode_project=True)
    fake_bin, command_log = _create_fake_devcontainer_commands(tmp_path)
    development_env = project_dir / '.devcontainer/.env'
    existing_contents = (
        'COMPOSE_PROJECT_NAME=stop_devcontainer\n'
        'IMAGE_USER_ID=21001\n'
        'IMAGE_USER_PRIMARY_GROUP_ID=21002\n'
        f'HOST_WORKSPACE={project_dir}\n'
        'HOST_XAUTHORITY_FILE=/tmp/docker-xwayland.xauth\n'
        'RENDER_GID=992\n'
        'DISPLAY=:99\n'
    )
    development_env.write_text(existing_contents)
    environment = os.environ.copy()
    environment.update({'COMMAND_LOG': str(command_log), 'PATH': f'{fake_bin}:{environment["PATH"]}'})

    completed = subprocess.run(
        [str(project_dir / '.devcontainer/devcont'), '--down'], text=True, capture_output=True, env=environment
    )

    assert completed.returncode == 0, completed.stdout + completed.stderr
    assert development_env.read_text() == existing_contents
    command_output = command_log.read_text()
    assert 'docker image inspect' not in command_output
    assert 'docker compose version' in command_output
    assert 'docker compose --project-directory' in command_output
    assert 'docker-compose.yaml down' in command_output


