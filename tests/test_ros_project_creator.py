def test_create_ros2_project_with_vscode_copies_the_project_compose(fake_active_user: Path) -> None:
    project_dir = fake_active_user / 'demo_vscode'

    _create_project(project_dir, img_id='demo/vscode:latest', use_vscode_project=True)

    docker_compose = project_dir / 'docker/compose_files/docker-compose.yaml'
    devcontainer_compose = project_dir / '.devcontainer/docker-compose.yaml'
    devcontainer_file = project_dir / '.devcontainer/devcontainer.json'
    code_devcont_script = project_dir / '.devcontainer/code-devcont'
    devcont_script = project_dir / '.devcontainer/devcont'

    for generated_file in (
        devcontainer_file,
        code_devcont_script,
        devcont_script,
        devcontainer_compose,
        project_dir / '.vscode/c_cpp_properties.json',
        project_dir / '.vscode/tasks.json',
        project_dir / 'ws.code-workspace',
    ):
        assert generated_file.is_file()
        assert '{{ image_name }}' not in generated_file.read_text()

    # Both use cases receive the same complete runtime configuration. They are
    # separate files so a developer can later customize only .devcontainer.
    assert devcontainer_compose.read_bytes() == docker_compose.read_bytes()

    compose_text = devcontainer_compose.read_text()
    compose_config = Utilities.load_yaml(devcontainer_compose)
    assert compose_config['name'] == '${COMPOSE_PROJECT_NAME:-demo}'
    service = next(iter(compose_config['services'].values()))
    workspace_mount = next(
        mount
        for mount in service['volumes']
        if isinstance(mount, dict) and mount.get('source', '').startswith('${HOST_WORKSPACE:')
    )
    assert 'demo/vscode:latest' in compose_text
    assert workspace_mount['type'] == 'bind'
    assert workspace_mount['target'] == '/workspace'
    assert workspace_mount['bind']['create_host_path'] is False
    assert '#   source: "${HOST_WORKSPACE:' not in compose_text
    assert 'CONTAINER_ROS_WORKSPACE: "/workspace"' in compose_text
    assert '# cap_add:' in compose_text
    assert '#   - NET_ADMIN' in compose_text
    assert '# ulimits:' in compose_text
    assert '#   rtprio:' in compose_text
    assert '#   memlock:' in compose_text
    assert service['stop_grace_period'] == '30s'
    assert 'HOST_UID' not in compose_text
    assert 'HOST_UPGID' not in compose_text
    assert 'user: root' not in compose_text
    assert 'driver: nvidia' not in compose_text

    devcontainer = json.loads(devcontainer_file.read_text())
    assert devcontainer['dockerComposeFile'] == 'docker-compose.yaml'
    assert devcontainer['service'] == 'demo_vscode_latest_cont'
    assert devcontainer['updateRemoteUserUID'] is False
    assert devcontainer['overrideCommand'] is False
    assert 'containerUser' not in devcontainer
    assert 'remoteUser' not in devcontainer
    assert devcontainer['workspaceFolder'] == '/workspace'

    assert os.access(code_devcont_script, os.X_OK)
    assert os.access(devcont_script, os.X_OK)
    assert 'HOST_WORKSPACE' in code_devcont_script.read_text()
    assert 'HOST_WORKSPACE' in devcont_script.read_text()
    assert 'IMAGE_USER_ID' in code_devcont_script.read_text()
    assert 'IMAGE_USER_PRIMARY_GROUP_ID' in code_devcont_script.read_text()
    assert 'robotics_dockers_user_env.py' in code_devcont_script.read_text()
    assert 'IMAGE_USER_ID' in devcont_script.read_text()
    assert 'IMAGE_USER_PRIMARY_GROUP_ID' in devcont_script.read_text()
    assert 'robotics_dockers_user_env.py' in devcont_script.read_text()
    assert 'COMPOSE_PROJECT_NAME="${COMPOSE_PROJECT_NAME:-demo}"' in code_devcont_script.read_text()
    assert 'print_compose_env_assignment COMPOSE_PROJECT_NAME' in devcont_script.read_text()
    assert 'docker image inspect' not in code_devcont_script.read_text()
    assert 'docker image inspect' not in devcont_script.read_text()
    assert 'HOST_UID' not in code_devcont_script.read_text()
    assert 'HOST_UPGID' not in devcont_script.read_text()
    assert not project_dir.joinpath('.devcontainer/.env').exists()

    # Editor and Dev Container files are per-developer starting points. The
    # generated repository must not start tracking later local customizations.
    gitignore_lines = project_dir.joinpath('.gitignore').read_text().splitlines()
    assert '.devcontainer/' in gitignore_lines
    assert '.vscode/' in gitignore_lines
    assert '*.code-workspace' in gitignore_lines


