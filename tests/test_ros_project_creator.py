def _create_fake_devcontainer_commands(tmp_path: Path) -> tuple[Path, Path]:
    """Create deterministic Docker and VS Code commands for generated-script tests."""
    fake_bin = tmp_path / 'fake-bin'
    fake_bin.mkdir()
    command_log = tmp_path / 'commands.log'

    fake_docker = fake_bin / 'docker'
    fake_docker.write_text(
        """#!/usr/bin/env bash
set -u
printf 'docker' >>"${COMMAND_LOG}"
printf ' %q' "$@" >>"${COMMAND_LOG}"
printf '\n' >>"${COMMAND_LOG}"

if [ "${1:-}" = image ] && [ "${2:-}" = inspect ]; then
    printf '%s\n' '[{"Config":{"Env":[' \\
        '"ROBOTICS_DOCKERS_USER=developer",' \\
        '"ROBOTICS_DOCKERS_USER_ID=21001",' \\
        '"ROBOTICS_DOCKERS_USER_HOME=/home/developer",' \\
        '"ROBOTICS_DOCKERS_USER_PRIMARY_GROUP=robotics",' \\
        '"ROBOTICS_DOCKERS_USER_PRIMARY_GROUP_ID=21002"' \\
        ']}}]'
fi
"""
    )
    fake_docker.chmod(0o755)

    fake_code = fake_bin / 'code'
    fake_code.write_text(
        """#!/usr/bin/env bash
set -u
printf 'code %s\n' "$*" >>"${COMMAND_LOG}"
printf 'identity=%s:%s\n' \\
    "${IMAGE_USER_ID:-}" \\
    "${IMAGE_USER_PRIMARY_GROUP_ID:-}" >>"${COMMAND_LOG}"
printf 'compose-project=%s\n' "${COMPOSE_PROJECT_NAME:-}" >>"${COMMAND_LOG}"
"""
    )
    fake_code.chmod(0o755)

    return fake_bin, command_log


